function textWidth(text, scale = 1) {
  let w = 0;
  for (const ch of String(text).toUpperCase()) w += ((FONT_ROWS[ch] || FONT_ROWS[' '])[0].length + 1) * scale;
  return Math.max(0, w - scale);
}

function drawText(ctx, text, x, y, { color = '#ffffff', scale = 1, align = 'left', shadow = '#000000' } = {}) {
  text = String(text).toUpperCase();
  const width = textWidth(text, scale);
  const left = Math.round(align === 'center' ? x - width / 2 : align === 'right' ? x - width : x);
  const top = Math.round(y);
  const pass = (offset, colour) => {
    ctx.fillStyle = colour;
    let cx = left;
    for (const ch of text) {
      const rows = FONT_ROWS[ch] || FONT_ROWS[' '];
      for (let r = 0; r < 7; r++) {
        for (let c = 0; c < rows[r].length; c++) {
          if (rows[r][c] === '#') ctx.fillRect(cx + c * scale + offset, top + r * scale + offset, scale, scale);
        }
      }
      cx += (rows[0].length + 1) * scale;
    }
  };
  if (shadow) pass(Math.max(1, Math.ceil(scale / 2)), shadow);
  pass(0, color);
}
